function canonical(value: string) {
  return value.normalize("NFC").replace(/[ʻʼ‘’]/g, "'").replace(/\s+/g, " ").trim();
}
const indexed = (catalog: Catalog): Record<string, string> =>
  Object.fromEntries(Object.entries(catalog).map(([key, value]) => [canonical(key), value]));

export type AppLanguage = "uz" | "ru" | "en";
export const APP_LANGUAGES: { id: AppLanguage; name: string; greeting: string }[] = [
  { id: "uz", name: "Oʻzbekcha", greeting: "Salom" },
  { id: "ru", name: "Русский", greeting: "Привет" },
  { id: "en", name: "English", greeting: "Hello" },
];
export const localePack: Record<Exclude<AppLanguage, "uz">, Record<string, string>> = {
  ru: indexed(russian),
  en: indexed(english),
};
export function translate(value: string, language: AppLanguage): string {
  if (language === "uz") return value;
  const normalized = canonical(value);
  const dictionary = localePack[language];
  return dictionary[normalized] ?? dictionary[canonical(aliases[normalized] ?? "")] ?? value;
}
